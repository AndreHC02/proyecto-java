    void listarEmpleados() {

    modelo.setNumRows(0);

    for (int i = 0; i < gestionEmpleado.obtenerCantidad(); i++) {

        Empleado emp = gestionEmpleado.getEmpleados()[i];

        String rol = "";

        if (emp instanceof Administrador) {
            rol = "Administrador";
        } else if (emp instanceof AsesorViaje) {
            rol = "Asesor de Viaje";
        } else if (emp instanceof Operador) {
            rol = "Operador";
        }

        Object[] fila = {
            emp.getIdEmpleado(),
            emp.getNombre(),
            emp.getApellido(),
            rol
        };

        modelo.addRow(fila);
    }
}

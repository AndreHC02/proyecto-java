    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
            int id = Integer.parseInt(txtID.getText().trim());
    String nombre = txtNombres.getText().trim();
    String apellido = jTextField3.getText().trim();
    String dni = jTextField4.getText().trim();
    String telefono = txtTelefono.getText().trim();
    String correo = txtCorreo.getText().trim();
    double sueldo = Double.parseDouble(txtSueldo.getText().trim());

    String rol = cbRol.getSelectedItem().toString();

    Empleado empleado;

    if (rol.equals("Administrador")) {

        empleado = new Administrador(id, nombre, apellido,
                dni, telefono, correo, sueldo, "Administración");

    } else if (rol.equals("Asesor de Viaje")) {

        empleado = new AsesorViaje(id, nombre, apellido,
                dni, telefono, correo, sueldo, 0);

    } else {

        empleado = new Operador(id, nombre, apellido,
                dni, telefono, correo, sueldo, "Mañana");

    }

    if (gestionEmpleado.actualizar(empleado)) {

        listarEmpleados();
        limpiar();

        JOptionPane.showMessageDialog(this, "Empleado actualizado");

    } else {

        JOptionPane.showMessageDialog(this, "No se encontró el empleado");

    }

    }//GEN-LAST:event_btnActualizarActionPerformed


    private void actualizarTabla(PaquetesTuristicos paquete) {
        
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaItinerario.getModel();
        
        
        modelo.setRowCount(0); 
        
        
        String[] dias = paquete.getItinerarioDias(); 
        
        
        for (int i = 0; i < dias.length; i++) {
            String texto = dias[i];
            
            
            if (texto == null || texto.trim().isEmpty()) {
                texto = "--- (Sin actividad registrada aún) ---";
            }
            
            
            modelo.addRow(new Object[]{ "Día " + (i + 1), texto });
        }
    }


    private void cboPaquetesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboPaquetesActionPerformed
        // TODO add your handling code here:
        int indice = cboPaquetes.getSelectedIndex();
        
        if (indice >= 0 && misPaquetes != null && misPaquetes[indice] != null) {
            PaquetesTuristicos paqueteElegido = misPaquetes[indice];
            
            
            lblDuracion.setText("Duración total del viaje:  " + paqueteElegido.getDdias() + " días");
            
            
            int maxDias = paqueteElegido.getDdias();
            spnDia.setModel(new javax.swing.SpinnerNumberModel(1, 1, maxDias, 1));
            
           
            actualizarTabla(paqueteElegido);
        }
    }//GEN-LAST:event_cboPaquetesActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        int indice = cboPaquetes.getSelectedIndex();
    
    if (indice == -1 || misPaquetes[indice] == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un paquete primero.");
        return;
    }
    
    PaquetesTuristicos paqueteElegido = misPaquetes[indice];
    
    
    int diaSeleccionado = (int) spnDia.getValue();
    String descripcion = txtActividad.getText().trim();
    
    if (descripcion.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, escriba la descripción de la actividad.", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    
    paqueteElegido.registrarActividadDia(diaSeleccionado, descripcion);
    
    
    javax.swing.JOptionPane.showMessageDialog(this, "¡Actividad del Día " + diaSeleccionado + " guardada exitosamente!");
    txtActividad.setText("");
    
    
    actualizarTabla(paqueteElegido);
    }//GEN-LAST:event_btnGuardarActionPerformed


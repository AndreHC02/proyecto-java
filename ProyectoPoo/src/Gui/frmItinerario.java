    private void cargarPaquetesEnCombo() {
        
        cboPaquetes.setModel(new javax.swing.DefaultComboBoxModel<>());
        cboPaquetes.removeAllItems(); 
        
        // 🔒 PROTECCIÓN: Si el arreglo está vacío (null), salimos
        if (this.misPaquetes == null) {
            return;
        }
        
        // Si tiene datos, recién corre el bucle for
        for (int i = 0; i < misPaquetes.length; i++) {
            if (misPaquetes[i] != null) { 
                cboPaquetes.addItem(misPaquetes[i].getIdCodigo() + " - " + misPaquetes[i].getNombre());
            }
        }
    }
    
